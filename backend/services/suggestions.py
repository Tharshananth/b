"""
Suggested follow-up questions.

Derived from what the tools actually returned, not generated by a second model
call. Two reasons: an extra round trip would roughly double the cost and
latency of every message, and a generated suggestion can propose something the
data does not support - "would you like me to restart the pipeline?" when no
such tool exists. Rules can only offer what is genuinely answerable.

Suggestions are optional. The user picks one or ignores them.
"""
import logging
from typing import Any, Dict, List

logger = logging.getLogger(__name__)

MAX_SUGGESTIONS = 3


def _job_suggestions(jobs: List[Dict[str, Any]]) -> List[str]:
    """Follow-ups implied by a set of job summaries."""
    out: List[str] = []
    if not jobs:
        return out

    failed = [j for j in jobs if j.get("overall") == "failed"]
    stalled = [j for j in jobs if j.get("overall") == "stalled"]

    # Cause-specific next questions. The wording mirrors the cause text so the
    # user can see the suggestion follows from what they were just told.
    for job in failed:
        for diag in job.get("diagnosis") or []:
            cause = (diag.get("cause") or "").lower()
            if "consent" in cause:
                out.append("How do I upload the missing consent forms?")
            elif "upload failed" in cause:
                out.append("What are the upload requirements for these series?")
            elif "internal" in cause:
                out.append("What information should I include when I contact support?")

    if stalled:
        out.append("How long should this stage normally take?")

    if len(jobs) == 1:
        job = jobs[0]
        pid = job.get("patient_id")
        if job.get("overall") != "completed":
            out.append("Show me the full stage-by-stage breakdown")
        if pid:
            out.append(f"Are there other scans for patient {pid}?")
    elif len(jobs) > 1:
        out.append("Which of these need attention first?")

    return out


def build(tool_calls: List[Any]) -> List[str]:
    """
    Suggestions for the answer just given.

    `tool_calls` are the orchestrator's ToolInvocation records. Only successful
    ones contribute - there is nothing useful to suggest off a failed lookup
    beyond what the answer already said.
    """
    out: List[str] = []

    for call in tool_calls:
        if not call.ok:
            continue
        if call.name == "get_job_status" and isinstance(call.payload, list):
            out.extend(_job_suggestions(call.payload))
        elif call.name == "search_knowledge_base":
            out.append("Can you show me the source documents for this?")

    # Preserve order, drop repeats, cap.
    seen = set()
    unique = [s for s in out if not (s in seen or seen.add(s))]
    return unique[:MAX_SUGGESTIONS]
